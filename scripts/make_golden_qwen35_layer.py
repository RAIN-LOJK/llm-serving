#!/usr/bin/env python
"""Generate the W5 single-layer golden fixture from Qwen3.5-0.8B (HF reference).

W5 aligns the hand-written full-attention layer against HF *stage by stage*, not just at
the block output (docs/w5-plan.md §4 Step 3). This script runs the HF text decoder once per
prompt on CPU in float32 with eager attention, hooks every stage of two full-attention
layers (3 = first, 23 = last), and writes ``meta.json`` + ``tensors.npz``.

    python scripts/make_golden_qwen35_layer.py --layers 3 23 --out /tmp/w5-golden-dry

The output directory is the only writable target; ``tests/golden/`` is generated by the
user after review and is read-only afterwards (tests/golden/README.md).

Two environment facts this script has to neutralise:

* **P-15.** ``causal-conv1d`` / ``fla`` are installed here; transformers resolves their
  kernels at import time and calls them unconditionally, and the CUDA wrappers assert
  ``x.is_cuda()``. Merely *loading* 0.8B on CPU then fails inside the 18 linear-attention
  layers ("Expected x.is_cuda()"), even though only full-attention layers are captured.
  The three symbols are pinned back to their torch fallbacks before the first forward.
* **P-14.** The checkpoint is ``Qwen3_5ForConditionalGeneration``; the decoder must be
  loaded from ``config.get_text_config()`` explicitly, otherwise vision + MTP weights come
  along (or the load fails on a missing ``vocab_size``).

Stages captured per layer (all float32, batch 1):

    layer_in          block input (residual stream)         (T, hidden), all positions
    input_layernorm   layer.input_layernorm output          (T, hidden)
    q_proj            layer.self_attn.q_proj output         (T, 2 * H * D)
    q_norm/k_norm     q/k after the zero-centered norm      (T, H|H_kv, D)
    gate              q_proj.view(T, H, 2D).chunk(2)[1]     (T, H, D)
    q_rope/k_rope     HF apply_rotary_pos_emb(q_norm/k_norm) (T, H|H_kv, D)
    attn_gated        o_proj forward_pre_hook input          (T, H * D)
    layer_out         layer output (residual included)       (T, hidden)

``q_proj``/``gate``/``attn_gated`` and the other wide stages are stored at three positions
(``0``, ``T // 2``, ``T - 1``); ``q_rope``/``k_rope`` are stored at every position because
RoPE errors show up as a position-dependent drift, and ``layer_in`` (the block's residual
input, which the test cannot rebuild from a single layer's weights) is stored in full as
well. ``{prompt}/positions`` records which rows
the sampled stages hold, so the test never re-derives the sampling rule.

npz keys: ``L{layer}/{prompt}/{stage}`` plus ``{prompt}/input_ids`` and
``{prompt}/positions``.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import platform
import sys
from datetime import datetime, timezone
from pathlib import Path

import numpy as np
import torch

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from scripts.make_golden import git_state, resolve_snapshot, slug_of  # noqa: E402

SPEC = "w5-golden-v1"
DEFAULT_REPO = "Qwen/Qwen3.5-0.8B"
DEFAULT_LAYERS = (3, 23)
DEFAULT_IDS = "s01,m01"
#: Per-prompt token budget: ``s01`` is short and kept whole; ``m01`` is truncated to 64.
TRUNCATIONS = {"s01": None, "m01": 64}
SAMPLED_STAGES = (
    "input_layernorm",
    "q_proj",
    "q_norm",
    "k_norm",
    "gate",
    "attn_gated",
    "layer_out",
)
#: Stages that come straight out of a module hook; ``gate``/``q_rope``/``k_rope`` are
#: derived from ``q_proj``/``q_norm``/``k_norm`` exactly as HF derives them.
HOOKED_STAGES = (
    "layer_in",
    "input_layernorm",
    "q_proj",
    "q_norm",
    "k_norm",
    "attn_gated",
    "layer_out",
)
FULL_STAGES = ("layer_in", "q_rope", "k_rope")
MAX_BYTES = 10 * 1024 * 1024


# ------------------------------------------------------------------ environment pins


def pin_torch_kernels() -> list[str]:
    """P-15: force transformers' Qwen3.5 kernels back to the torch fallbacks (in place)."""
    from transformers.models.qwen3_5 import modeling_qwen3_5 as q35

    pinned = []
    for name in ("causal_conv1d_fn", "causal_conv1d_update", "torch_chunk_gated_delta_rule"):
        fn = getattr(q35, name, None)
        fallback = getattr(fn, "__wrapped__", None)
        if fallback is not None and fallback is not fn:
            setattr(q35, name, fallback)
            pinned.append(name)
    return pinned


def cap_torch_threads() -> int:
    """Pin the BLAS thread count, mirroring ``tests/conftest.py``.

    A CPU fp32 matmul is deterministic for a fixed thread count but not across counts (the
    K-reduction order changes), and the test gate caps threads at 16. Pinning both sides to
    the same cap makes the projection stages bit-identical, so a nonzero ``q_proj`` delta in
    the alignment table means a real wiring bug instead of cross-process summation noise.
    ``MINILLM_TORCH_THREADS`` overrides, exactly like the test gate.
    """
    import os

    wanted = int(os.environ.get("MINILLM_TORCH_THREADS", "0")) or min(16, os.cpu_count() or 1)
    torch.set_num_threads(wanted)
    return wanted


def load_text_decoder(snapshot: Path, device: torch.device):
    """P-14: load the *text* decoder of the multimodal checkpoint, fp32, eager attention."""
    from transformers import AutoConfig, AutoModelForCausalLM, AutoTokenizer

    hf_config = AutoConfig.from_pretrained(snapshot, local_files_only=True)
    text_config = hf_config.get_text_config()
    model = AutoModelForCausalLM.from_pretrained(
        snapshot,
        config=text_config,
        dtype=torch.float32,
        local_files_only=True,
        attn_implementation="eager",
    )
    model.to(device).eval()
    tokenizer = AutoTokenizer.from_pretrained(snapshot, local_files_only=True)

    # The vision tower and the MTP head must not be part of the reference run.
    names = {name for name, _ in model.named_parameters()}
    leaked = sorted(n for n in names if n.startswith(("visual.", "mtp.", "model.visual.", "model.mtp.")))
    if leaked:
        raise SystemExit(f"text-only load leaked {len(leaked)} vision/MTP parameter(s): {leaked[:5]}")
    return model, tokenizer, text_config


# ------------------------------------------------------------------------ capturing


def _capture(name: str, layer_idx: int, store: dict):
    def hook(_module, _inputs, output):
        store[(layer_idx, name)] = output.detach()

    return hook


def _capture_input(name: str, layer_idx: int, store: dict):
    def hook(_module, inputs):
        store[(layer_idx, name)] = inputs[0].detach()

    return hook


def register_hooks(model, layers: list[int]) -> tuple[dict, list]:
    store: dict[tuple[int, str], torch.Tensor] = {}
    handles = []
    for layer_idx in layers:
        layer = model.model.layers[layer_idx]
        attention = layer.self_attn
        handles += [
            layer.register_forward_hook(_capture("layer_out", layer_idx, store)),
            # The block's own input is the residual stream from the layers below; the
            # alignment test cannot rebuild it, so it is stored in full (all positions,
            # because every position's attention needs the earlier keys).
            layer.register_forward_pre_hook(_capture_input("layer_in", layer_idx, store)),
            layer.input_layernorm.register_forward_hook(
                _capture("input_layernorm", layer_idx, store)
            ),
            attention.q_proj.register_forward_hook(_capture("q_proj", layer_idx, store)),
            attention.q_norm.register_forward_hook(_capture("q_norm", layer_idx, store)),
            attention.k_norm.register_forward_hook(_capture("k_norm", layer_idx, store)),
            # The gated attention output is o_proj's *input* (the gate multiply happens
            # between attention and o_proj, and has no module of its own).
            attention.o_proj.register_forward_pre_hook(
                _capture_input("attn_gated", layer_idx, store)
            ),
        ]
    return store, handles


def rope_tables(model, embed_out: torch.Tensor, length: int):
    """HF text rotary table, ``(1, T, rotary_dim)`` per component (positions 0..T-1)."""
    position_ids = torch.arange(length, device=embed_out.device)[None, None, :].expand(3, 1, length)
    cos, sin = model.model.rotary_emb(embed_out, position_ids)
    return cos, sin


def sampled_positions(length: int) -> list[int]:
    return sorted({0, length // 2, length - 1})


# ---------------------------------------------------------------------------- main


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--model", default=DEFAULT_REPO)
    ap.add_argument("--revision", default=None, help="commit hash; defaults to the cached refs/main")
    ap.add_argument("--model-path", default=None, help="local snapshot dir (skips cache lookup)")
    ap.add_argument("--layers", type=int, nargs="+", default=list(DEFAULT_LAYERS))
    ap.add_argument("--ids", default=DEFAULT_IDS)
    ap.add_argument(
        "--out",
        default=str(ROOT / "tests" / "golden" / "qwen35-0-8b" / "0001"),
        help="output dir (must be empty); tests/golden/ is user-generated after review",
    )
    ap.add_argument("--device", default="cpu", help="cpu (default) or cuda when RAM is short")
    args = ap.parse_args()

    device = torch.device(args.device)
    if device.type == "cuda" and not torch.cuda.is_available():
        raise SystemExit("--device cuda requested but CUDA is not available")

    if args.model_path:
        snapshot, revision = Path(args.model_path), Path(args.model_path).name
    else:
        snapshot, revision = resolve_snapshot(args.model, args.revision)

    out_dir = Path(args.out)
    if out_dir.exists() and any(out_dir.iterdir()):
        raise SystemExit(
            f"{out_dir} already has a fixture; golden is immutable — bump the id "
            "(tests/golden/README.md)"
        )

    threads = cap_torch_threads()
    pinned = pin_torch_kernels()
    model, tokenizer, text_config = load_text_decoder(snapshot, device)
    torch.set_grad_enabled(False)

    n_head = int(text_config.num_attention_heads)
    n_kv_head = int(text_config.num_key_value_heads)
    head_dim = int(getattr(text_config, "head_dim", None) or text_config.hidden_size // n_head)
    from transformers.models.qwen3_5.modeling_qwen3_5 import apply_rotary_pos_emb

    prompt_ids = [p.strip() for p in args.ids.split(",") if p.strip()]
    prompt_texts = _load_prompt_texts(prompt_ids)
    layers = [int(layer) for layer in args.layers]
    for layer_idx in layers:
        kind = text_config.layer_types[layer_idx]
        if kind != "full_attention":
            raise SystemExit(f"layer {layer_idx} is {kind!r}; W5 golden needs full_attention layers")

    arrays: dict[str, np.ndarray] = {}
    prompt_meta = []
    for prompt_id in prompt_ids:
        tokens = tokenizer(prompt_texts[prompt_id], return_tensors="pt").input_ids
        budget = TRUNCATIONS.get(prompt_id)
        truncation = "none (full prompt)"
        if budget is not None and tokens.shape[1] > budget:
            tokens = tokens[:, :budget]
            truncation = f"first {budget} tokens of the tokenizer output"
        input_ids = tokens.to(device)
        length = int(input_ids.shape[1])
        positions = sampled_positions(length)

        store, handles = register_hooks(model, layers)
        try:
            model(input_ids)
        finally:
            for handle in handles:
                handle.remove()

        embed_out = model.model.embed_tokens(input_ids)
        cos, sin = rope_tables(model, embed_out, length)
        assert cos.shape == (1, length, int(head_dim * text_config.rope_parameters["partial_rotary_factor"]))

        arrays[f"{prompt_id}/input_ids"] = input_ids[0].to(torch.int32).cpu().numpy()
        arrays[f"{prompt_id}/positions"] = np.asarray(positions, dtype=np.int32)

        index = torch.tensor(positions, device=device)
        for layer_idx in layers:
            stages = {}
            for name in HOOKED_STAGES:
                stages[name] = store[(layer_idx, name)]
            q_proj_out = store[(layer_idx, "q_proj")]
            gate = q_proj_out.view(1, length, n_head, 2 * head_dim).chunk(2, dim=-1)[1]
            q_rope, k_rope = apply_rotary_pos_emb(
                store[(layer_idx, "q_norm")].transpose(1, 2),
                store[(layer_idx, "k_norm")].transpose(1, 2),
                cos,
                sin,
            )
            stages["gate"] = gate
            stages["q_rope"] = q_rope.transpose(1, 2)
            stages["k_rope"] = k_rope.transpose(1, 2)

            for name, tensor in stages.items():
                # Full stages keep every position; the wide ones keep the 3 sampled rows.
                selected = tensor if name in FULL_STAGES else tensor.index_select(1, index)
                arrays[f"L{layer_idx}/{prompt_id}/{name}"] = (
                    selected[0].to(torch.float32).cpu().numpy()
                )

        prompt_meta.append(
            {
                "id": prompt_id,
                "n_tokens": length,
                "truncation": truncation,
                "text_sha256": hashlib.sha256(prompt_texts[prompt_id].encode()).hexdigest(),
                "token_sha256": hashlib.sha256(
                    np.asarray(input_ids[0].cpu(), dtype=np.int32).tobytes()
                ).hexdigest(),
                "sampled_positions": positions,
                "input_ids": [int(token) for token in input_ids[0].cpu()],
            }
        )
        print(f"  {prompt_id}: {length} tokens ({truncation}), positions {positions}")

    out_dir.mkdir(parents=True, exist_ok=True)
    np.savez_compressed(out_dir / "tensors.npz", **arrays)

    meta = {
        "spec": SPEC,
        "model": {
            "repo": args.model,
            "revision": revision,
            "slug": slug_of(args.model),
            "class": type(model).__name__,
            "config_class": type(text_config).__name__,
            "dtype": "float32",
            "device": str(device),
            "attn_implementation": "eager",
            "n_params": sum(p.numel() for p in model.parameters()),
            "n_layer": int(text_config.num_hidden_layers),
            "n_head": n_head,
            "n_kv_head": n_kv_head,
            "head_dim": head_dim,
            "rotary_dim": int(
                head_dim * text_config.rope_parameters.get("partial_rotary_factor", 1.0)
            ),
        },
        "tokenizer": {
            "repo": args.model,
            "revision": revision,
            "class": type(tokenizer).__name__,
        },
        "prompts": prompt_meta,
        "truncation": {
            prompt_id: TRUNCATIONS.get(prompt_id) for prompt_id in prompt_ids
        },
        "layers": layers,
        "stages": {
            "sampled": list(SAMPLED_STAGES),
            "full": list(FULL_STAGES),
            "rules": {
                "input_layernorm": "layer.input_layernorm output, float32 (n_pos, hidden)",
                "q_proj": "layer.self_attn.q_proj output (n_pos, n_head * head_dim * 2)",
                "q_norm": "q_proj.view(T, n_head, 2D).chunk(2)[0] after q_norm (n_pos, n_head, D)",
                "k_norm": "k_proj.view(T, n_kv_head, D) after k_norm (n_pos, n_kv_head, D)",
                "gate": "q_proj.view(T, n_head, 2D).chunk(2)[1] (n_pos, n_head, D)",
                "q_rope": "HF apply_rotary_pos_emb(q_norm^T) -> (n_pos, n_head, D), all positions",
                "k_rope": "HF apply_rotary_pos_emb(k_norm^T) -> (n_pos, n_kv_head, D), all positions",
                "attn_gated": "o_proj forward_pre_hook input: attn_out * sigmoid(gate) (n_pos, H*D)",
                "layer_in": "decoder layer input (residual stream), all positions (T, hidden)",
                "layer_out": "decoder layer output, residual included (n_pos, hidden)",
            },
            "sampled_positions": "sorted({0, T // 2, T - 1}); see {prompt}/positions in the npz",
        },
        "tensors": {
            "npz_keys": "L{layer}/{prompt}/{stage}; plus {prompt}/input_ids and {prompt}/positions",
            "input_ids": "int32 (T,) token ids the HF reference consumed",
            "positions": "int32 (n_sampled,) rows present for the sampled stages",
        },
        "versions": {
            "python": platform.python_version(),
            "torch": torch.__version__,
            "transformers": __import__("transformers").__version__,
            "numpy": np.__version__,
        },
        "environment": {"pinned_kernels": pinned, "torch_threads": threads},
        "source": {**git_state(), "command": " ".join(sys.argv)},
        "created_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
    }
    (out_dir / "meta.json").write_text(json.dumps(meta, indent=2, ensure_ascii=False) + "\n")

    size = sum(f.stat().st_size for f in out_dir.iterdir())
    print(f"\n✓ {out_dir}  ({size / 1e6:.2f} MB, limit {MAX_BYTES / 1e6:.0f} MB)")
    for layer_idx in layers:
        for prompt_id in prompt_ids:
            for stage in SAMPLED_STAGES + FULL_STAGES:
                tensor = arrays[f"L{layer_idx}/{prompt_id}/{stage}"]
                print(
                    f"   L{layer_idx}/{prompt_id}/{stage:<16} {str(tensor.shape):<18} "
                    f"max|ref|={np.abs(tensor).max():.3e}"
                )
    if size > MAX_BYTES:
        raise SystemExit(
            f"fixture is {size / 1e6:.1f} MB > {MAX_BYTES / 1e6:.0f} MB; shrink the sampled "
            "stages before committing"
        )
    return 0


def _load_prompt_texts(ids: list[str]) -> dict[str, str]:
    spec = json.loads((ROOT / "bench" / "prompts.json").read_text())
    by_id = {p["id"]: p["text"] for p in spec["prompts"]}
    missing = [prompt_id for prompt_id in ids if prompt_id not in by_id]
    if missing:
        raise SystemExit(f"unknown prompt ids {missing}; bench/prompts.json v{spec['version']}")
    return {prompt_id: by_id[prompt_id] for prompt_id in ids}


if __name__ == "__main__":
    raise SystemExit(main())
